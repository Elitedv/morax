import fsPromises from 'fs/promises';
import path from 'path';

export async function setupReadme(
  projectPath: string,
  workspaceName: string,
  options: {
    hasDb?: boolean;
    orm?: 'drizzle' | 'none';
    hasDocker?: boolean;
    dockerServices?: { postgres?: boolean; redis?: boolean };
  } = {},
) {
  const readmePath = path.join(projectPath, 'README.md');

  let dockerDocs: string[] = [];
  if (options.hasDocker) {
    dockerDocs = [
      '### Docker Infrastructure',
      'Manage local services from the workspace root:',
      '```bash',
      'pnpm docker:up       # Start all local docker services in background',
      'pnpm docker:down     # Stop all local docker services',
      ...(options.dockerServices?.postgres
        ? ['pnpm docker:db       # Start PostgreSQL service only']
        : []),
      ...(options.dockerServices?.redis
        ? ['pnpm docker:redis    # Start Redis service only']
        : []),
      '```',
      '',
    ];
  }

  let dbDocs: string[] = [];
  if (options.hasDb && options.orm === 'drizzle') {
    dbDocs = [
      '### Database (Drizzle ORM)',
      'Manage schema migrations, seeding, and visual database inspector:',
      '```bash',
      'pnpm --filter @repo/db db:push      # Push schema directly to database',
      'pnpm --filter @repo/db db:seed      # Seed starter database records',
      'pnpm --filter @repo/db db:studio    # Open Drizzle Studio visual GUI',
      'pnpm --filter @repo/db db:generate  # Generate migration SQL files',
      '```',
      '',
    ];
  }

  const readmeContent = [
    `# Morax `,
    '',
    'Welcome to your next-generation, high-performance monorepo workspace generated by **Morax**.',
    '',
    '## Workspace Structure',
    '',
    '- **`apps/`** — Frontend applications, backend servers, and user-facing services.',
    '- **`packages/`** — Shared modules, TypeScript configurations, and common utility libraries.',
    ...(options.hasDocker
      ? [
          '  - **`docker/`** — Local container infrastructure configurations (docker-compose.yml).',
        ]
      : []),
    ...(options.hasDb
      ? [
          `  - **\`packages/db\`** — Shared database schemas, migrations, and Drizzle ORM client.`,
        ]
      : []),
    '',
    '## Key Commands',
    '',
    'Run the following commands from the root directory of your workspace:',
    '',
    '### Development',
    'Start all dev servers and hot-reloading configurations concurrently:',
    '```bash',
    'pnpm dev',
    '```',
    '',
    ...dockerDocs,
    ...dbDocs,
    '### Linting',
    'Run static analysis across all workspaces:',
    '```bash',
    'pnpm lint',
    '```',
    '',
    '### Formatting',
    'Format all codebase files according to your chosen formatter:',
    '```bash',
    'pnpm format',
    '```',
    '',
    '---',
    '',
    '*Generated with love by [Morax Scaffolder CLI](https://github.com/Elitedv/morax).*',
    '',
  ].join('\n');

  await fsPromises.writeFile(readmePath, readmeContent, 'utf8');
}
