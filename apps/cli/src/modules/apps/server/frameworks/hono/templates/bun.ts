export function renderHonoBunTemplate(hasDb: boolean): string {
  const dbImport = hasDb ? ["import { db, users } from '@repo/db';"] : [];
  const userRoute = hasDb
    ? [
        '// Example endpoint querying shared database package (Drizzle ORM)',
        "app.get('/api/v1/user', async (c) => {",
        '  try {',
        '    const allUsers = await db.select().from(users);',
        '    return c.json({ users: allUsers });',
        '  } catch (error: any) {',
        '    return c.json({ error: error.message }, 500);',
        '  }',
        '});',
      ]
    : [
        '// Example user endpoint',
        "app.get('/api/v1/user', (c) => {",
        '  return c.json({',
        "    user: { id: '1', name: 'Demo User', email: 'demo@morax.dev' },",
        '  });',
        '});',
      ];

  return [
    "import { Hono } from 'hono';",
    "import { cors } from 'hono/cors';",
    ...dbImport,
    '',
    'const app = new Hono();',
    'if (!process.env.PORT) {',
    "  throw new Error('PORT environment variable is required');",
    '}',
    'const port = Number(process.env.PORT);',
    '',
    '// Enable CORS middleware',
    "app.use('*', cors());",
    '',
    '// Root route',
    "app.get('/', (c) => {",
    '  return c.json({',
    "    message: 'Welcome to the Morax Hono API (Bun)!',",
    "    status: 'healthy',",
    '  });',
    '});',
    '',
    '// Health check route',
    "app.get('/health', (c) => {",
    '  return c.json({',
    "    status: 'ok',",
    '    timestamp: new Date().toISOString(),',
    '  });',
    '});',
    '',
    ...userRoute,
    '',
    'console.log(`🚀 Hono server (Bun) running on http://localhost:${port}`);',
    '',
    'export { app };',
    'export default {',
    '  port,',
    '  fetch: app.fetch,',
    '};',
    '',
  ].join('\n');
}
