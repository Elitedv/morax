export function renderHonoNodeTemplate(hasDb: boolean): string {
  const dbImport = hasDb ? ["import { db, users } from '@repo/db';"] : [];
  const userRoute = hasDb
    ? [
        '// Example endpoint querying shared database package (Drizzle ORM)',
        "app.get('/api/v1/user', async (c) => {",
        '  try {',
        '    const allUsers = await db.select().from(users);',
        '    return c.json({ users: allUsers });',
        '  } catch (error: any) {',
        '    return c.json({ error: error.message }, 500);',
        '  }',
        '});',
      ]
    : [
        '// Example user endpoint',
        "app.get('/api/v1/user', (c) => {",
        '  return c.json({',
        "    user: { id: '1', name: 'Demo User', email: 'demo@morax.dev' },",
        '  });',
        '});',
      ];

  return [
    "import { Hono } from 'hono';",
    "import { serve } from '@hono/node-server';",
    "import { getRequestListener } from '@hono/node-server';",
    "import { cors } from 'hono/cors';",
    ...dbImport,
    '',
    'const app = new Hono();',
    'if (!process.env.PORT) {',
    "  throw new Error('PORT environment variable is required');",
    '}',
    'const port = Number(process.env.PORT);',
    '',
    '// Enable CORS middleware',
    "app.use('*', cors());",
    '',
    '// Root route',
    "app.get('/', (c) => {",
    '  return c.json({',
    "    message: 'Welcome to the Morax Hono API (Node.js)!',",
    "    status: 'healthy',",
    '  });',
    '});',
    '',
    '// Health check route',
    "app.get('/health', (c) => {",
    '  return c.json({',
    "    status: 'ok',",
    '    timestamp: new Date().toISOString(),',
    '  });',
    '});',
    '',
    ...userRoute,
    '',
    "if (process.env.NODE_ENV !== 'production' || !process.env.VERCEL) {",
    '  serve(',
    '    {',
    '      fetch: app.fetch,',
    '      port,',
    '    },',
    '    (info) => {',
    '      console.log(`🚀 Hono server running on http://localhost:${info.port}`);',
    '    },',
    '  );',
    '}',
    '',
    'export { app };',
    'export default getRequestListener(app.fetch);',
    '',
  ].join('\n');
}
