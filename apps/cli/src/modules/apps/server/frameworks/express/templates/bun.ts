export function renderExpressBunTemplate(hasDb: boolean): string {
  const dbImport = hasDb ? ["import { db, users } from '@repo/db';"] : [];
  const userRoute = hasDb
    ? [
        '// Example endpoint querying shared database package (Drizzle ORM)',
        "app.get('/api/v1/user', async (req, res) => {",
        '  try {',
        '    const allUsers = await db.select().from(users);',
        '    res.json({ users: allUsers });',
        '  } catch (error: any) {',
        '    res.status(500).json({ error: error.message });',
        '  }',
        '});',
      ]
    : [
        '// Example user endpoint',
        "app.get('/api/v1/user', (req, res) => {",
        '  res.json({',
        "    user: { id: '1', name: 'Demo User', email: 'demo@morax.dev' },",
        '  });',
        '});',
      ];

  return [
    "import express from 'express';",
    "import cors from 'cors';",
    ...dbImport,
    '',
    'const app = express();',
    'if (!process.env.PORT) {',
    "  throw new Error('PORT environment variable is required');",
    '}',
    'const port = Number(process.env.PORT);',
    '',
    '// Enable CORS and parsing of JSON request bodies',
    'app.use(cors());',
    'app.use(express.json());',
    '',
    '// Root route',
    "app.get('/', (req, res) => {",
    '  res.json({',
    "    message: 'Welcome to the Morax Express API (Bun)!',",
    "    status: 'healthy',",
    '  });',
    '});',
    '',
    '// Health check route',
    "app.get('/health', (req, res) => {",
    '  res.json({',
    "    status: 'ok',",
    '    timestamp: new Date().toISOString(),',
    '  });',
    '});',
    '',
    ...userRoute,
    '',
    "if (process.env.NODE_ENV !== 'production' || !process.env.VERCEL) {",
    '  app.listen(port, () => {',
    '    console.log(`🚀 Express server running on http://localhost:${port}`);',
    '  });',
    '}',
    '',
    'export default app;',
    '',
  ].join('\n');
}
